import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const raw = execFileSync(
  'cargo',
  ['run', '--quiet', '-p', 'knowledge-server', '--bin', 'openapi'],
  { cwd: root, encoding: 'utf8', windowsHide: true },
)
const document = JSON.parse(raw)

const operations = {}
for (const path of Object.keys(document.paths).sort()) {
  for (const method of Object.keys(document.paths[path]).sort()) {
    const operation = document.paths[path][method]
    operations[operation.operationId] = { method: method.toUpperCase(), path }
  }
}

const output = `// This file is generated by pnpm api:generate. Do not edit.
export type UUID = string

export interface Problem {
  type: string
  title: string
  status: number
  detail: string
  code: string
}

export interface Session {
  sessionId: UUID
  userId: UUID
  workspaceId: UUID
  workspaceAdmin: boolean
}

export interface Csrf { token: string }

export interface Settings {
  attachmentRecoveryDays: number
  exportRetentionHours: number
}

export interface Subject {
  id: UUID
  type: 'user' | 'group'
  label: string
  status: 'active'
}

export interface PageRevision {
  id: UUID
  pageId: UUID
  version: number
  title: string
  markdown: string
  properties: Record<string, unknown>
  authorId: UUID
  createdAt: string
}

export const operations = ${JSON.stringify(operations, null, 2)} as const
`

const target = resolve(root, 'apps/web/src/api/generated.ts')
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, output.replaceAll('\r\n', '\n'), 'utf8')
