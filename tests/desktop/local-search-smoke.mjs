// Real desktop IPC + UI, synthetic local vault only. Restore the original vault.
import assert from 'node:assert/strict'
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { connect } from './cdp-test-client.mjs'

const { socket, send, evaluate, waitFor, click, key, delay } = await connect()
const command = (name, args = {}) => evaluate(`window.__TAURI_INTERNALS__.invoke(${JSON.stringify(name)}, ${JSON.stringify(args)})`)
const original = await command('restore_vault')
assert.ok(original?.root, 'An existing vault is needed for restoration after QA')
const scratch = await mkdtemp(join(tmpdir(), 'brandon-search-'))
const passes = [], pass = text => { passes.push(text); console.log(`PASS ${text}`) }
const query = async (text, wait = true) => {
  await evaluate(`document.querySelector('input[aria-label="Поиск по vault"]').focus()`)
  await key('a', 'KeyA', 2)
  if (text) await send('Input.insertText', { text }); else await key('Backspace', 'Backspace')
  try { await waitFor(`document.querySelector('input[aria-label="Поиск по vault"]').value === ${JSON.stringify(text)}`) }
  catch (error) { console.error(await evaluate("({active:document.activeElement?.tagName,value:document.querySelector('input[aria-label=\"Поиск по vault\"]')?.value,selection:[document.querySelector('input[aria-label=\"Поиск по vault\"]')?.selectionStart,document.querySelector('input[aria-label=\"Поиск по vault\"]')?.selectionEnd]})")); throw error }
  if (wait) await waitFor(`document.querySelector('.local-search .sidebar-content')?.dataset.completedQuery === ${JSON.stringify(text)} && document.querySelector('.local-search .sidebar-content')?.getAttribute('aria-busy') === 'false'`)
}
try {
  await mkdir(join(scratch, 'Docs'))
  await writeFile(join(scratch, 'Docs', 'План.md'), '# План\n\nНачало.\n\n## Детали\n\nПривет мир renderer. #работа\nneedlejump here\nlet key = foo::bar(42);\nprintln!("Привет мир");\n')
  await writeFile(join(scratch, 'Другой.md'), '# Другой\n\nalpha beta gamma\n')
  await writeFile(join(scratch, 'Manual.pdf'), '%PDF-synthetic-name-only-not-a-real-document')
  await writeFile(join(scratch, 'token.txt'), 'privateuniquemarker')
  await writeFile(join(scratch, 'Board.canvas'), JSON.stringify({ nodes: [{ id: 'far-target', type: 'text', x: 9500, y: 5000, width: 300, height: 150, text: 'Карточка telescope' }], edges: [] }))
  await command('open_vault', { path: scratch }); await send('Page.reload')
  await waitFor("Boolean(document.querySelector('.tree-row'))")
  await click('button[aria-label="Поиск"]')
  await query('"привет мир" tag:работа')
  assert.equal(await evaluate("document.querySelectorAll('.search-results button').length"), 1)
  assert.equal(await evaluate("document.querySelector('.search-results button').dataset.path"), 'Docs/План.md')
  pass('Russian phrase and tag filter return the actual saved note')

  await query('needlejump path:Docs')
  await key('ArrowDown', 'ArrowDown')
  assert.equal(await evaluate("document.activeElement?.matches('.search-results button')"), true)
  await key('Enter', 'Enter')
  await waitFor("document.querySelector('.breadcrumbs strong')?.textContent === 'План'")
  await waitFor("window.getSelection()?.toString().includes('needlejump')")
  await send('Input.insertText', { text: 'search-selection-proof' })
  await waitFor("document.querySelector('.cm-content')?.textContent.includes('search-selection-proof') && document.querySelector('.save-button')?.disabled === false")
  await key('s', 'KeyS', 2)
  await waitFor("document.querySelector('.save-button')?.disabled === true && document.querySelector('.save-button')?.textContent.includes('Сохранено')")
  assert.equal((await readFile(join(scratch, 'Docs', 'План.md'), 'utf8')).split('\n')[7], 'search-selection-proof')
  await key('z', 'KeyZ', 2)
  await waitFor("document.querySelector('.cm-content')?.textContent.includes('needlejump') && document.querySelector('.save-button')?.disabled === false")
  await key('s', 'KeyS', 2)
  await waitFor("document.querySelector('.save-button')?.disabled === true && document.querySelector('.save-button')?.textContent.includes('Сохранено')")
  pass('Keyboard result navigation reveals and selects the exact Markdown line')
  await click('button[title="Чтение"]')
  await waitFor("!document.querySelector('.cm-content') && Boolean(document.querySelector('.preview-pane'))")
  await click('button[title="Редактор"]')
  await waitFor("Boolean(document.querySelector('.cm-content'))")
  await delay(100)
  assert.equal(await evaluate("window.getSelection()?.toString().includes('needlejump')"), false)
  pass('A consumed search jump does not steal focus again after toggling reading mode')

  await click('.local-search-options button:nth-child(2)')
  await query('foo::bar(42)')
  assert.equal(await evaluate("document.querySelectorAll('.search-results button').length"), 1)
  pass('Literal mode finds code punctuation without Markdown syntax tricks')
  await query('println!("Привет мир")')
  assert.equal(await evaluate("document.querySelectorAll('.search-results button').length"), 1)
  pass('Literal code queries preserve quotation marks and spaces')
  await click('.local-search-options button:first-child')
  await query('telescope')
  await click('.search-results button')
  await waitFor("document.querySelector('.canvas-view')?.dataset.searchFocusedNode === 'far-target'")
  await waitFor("document.querySelector('.canvas-view')?.dataset.renderer === 'wgpu'")
  assert.ok(await evaluate("document.querySelector('.canvas-world').style.transform.includes('-9650px')"))
  pass('Canvas result selects and centres the distant card on the normal GPU board')

  await query('Manual')
  await click('.search-results button')
  await waitFor("document.querySelector('.canvas-attachment-details h3')?.textContent === 'Manual.pdf'")
  assert.equal(await evaluate("document.querySelector('.breadcrumbs strong')?.textContent"), 'Board')
  assert.ok(await evaluate("document.querySelector('.search-results p').textContent.includes('не индексировалось')"))
  await click('button[aria-label="Закрыть вложение"]')
  pass('Binary matches are explicitly name-only and open the attachment peek, not a Markdown editor')

  await query('privateuniquemarker')
  assert.equal(await evaluate("document.querySelectorAll('.search-results button').length"), 0)
  pass('Credential filenames do not leak into search')

  await command('create_task', { title: 'Проверить дедлайн', scheduled: '2026-10-21' })
  await query('', false)
  await evaluate("(()=>{ const select=document.querySelector('select[aria-label=\"Тип результатов\"]'); select.value='task'; select.dispatchEvent(new Event('change',{bubbles:true})); })()")
  await waitFor("document.querySelector('.search-results button')?.dataset.path === 'Tasks/Проверить дедлайн.md'")
  assert.equal(await evaluate("document.querySelectorAll('.search-results button').length"), 1)
  await click('.local-search-options button:nth-child(2)')
  await query('2026-10-21')
  await click('.search-results button')
  await waitFor("document.querySelector('.breadcrumbs strong')?.textContent === 'Проверить дедлайн'")
  await waitFor("window.getSelection()?.toString().includes('Проверить дедлайн')")
  pass('Task-only filter works without a text query and operational dates open the real task note')
  await evaluate("(()=>{ const select=document.querySelector('select[aria-label=\"Тип результатов\"]'); select.value=''; select.dispatchEvent(new Event('change',{bubbles:true})); })()")
  await click('.local-search-options button:first-child')

  await query('newexternalmarker')
  assert.equal(await evaluate("document.querySelectorAll('.search-results button').length"), 0)
  await writeFile(join(scratch, 'Другой.md'), '# Другой\n\nnewexternalmarker arrived externally\n')
  await waitFor("document.querySelector('.search-results button')?.dataset.path === 'Другой.md'")
  assert.equal(await evaluate("document.querySelector('.search-results strong')?.textContent"), 'Другой')
  pass('External file edits refresh an unchanged active query')

  await query('telescope', false)
  await delay(250)
  await query('newexternalmarker')
  await delay(450)
  assert.equal(await evaluate("document.querySelector('.search-results button')?.dataset.path"), 'Другой.md')
  await evaluate(`(() => { window.__qaBusyChanges = 0; window.__qaBusyObserver = new MutationObserver(() => window.__qaBusyChanges++); window.__qaBusyObserver.observe(document.querySelector('.local-search .sidebar-content'), { attributes: true, attributeFilter: ['aria-busy'] }); })()`)
  await delay(1200)
  assert.equal(await evaluate('window.__qaBusyChanges'), 0)
  await evaluate('window.__qaBusyObserver.disconnect()')
  pass('Rapid query changes preserve the latest result and cache writes do not cause a refresh loop')
  await click('.search-results button')
  await waitFor("document.querySelector('.breadcrumbs strong')?.textContent === 'Другой'")
  if (process.env.BRANDON_QA_SCREENSHOT) {
    const screenshot = await send('Page.captureScreenshot', { format: 'png' })
    await writeFile(process.env.BRANDON_QA_SCREENSHOT, Buffer.from(screenshot.data, 'base64'))
  }
  const report = fileURLToPath(new URL('../../target/qa/local-search.json', import.meta.url))
  await mkdir(join(report, '..'), { recursive: true })
  await writeFile(report, JSON.stringify({ date: new Date().toISOString(), passes, scratch, notes: 'Synthetic fixtures; actual desktop IPC, keyboard input, native GPU board and watcher. No user document contents are captured.' }, null, 2))
  console.log(JSON.stringify({ passed: passes.length, report }))
  assert.equal((await readFile(join(scratch, 'Docs', 'План.md'), 'utf8')).includes('needlejump'), true)
} finally {
  await evaluate('window.__qaBusyObserver?.disconnect()')
  await command('open_vault', { path: original.root }); await send('Page.reload'); socket.close()
}
